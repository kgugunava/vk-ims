#!/usr/bin/env python3
"""Generate msgfmt/src/unicode_tables.inc.

The markup rules treat `_` as a word boundary only next to a character that is
not a letter or digit. msgfmt reads "letter or digit" as Unicode general
categories L* (Lu, Ll, Lt, Lm, Lo) and Nd. This script dumps those categories
as sorted, merged code point ranges, using the Unicode database bundled with
Python, so the C++ side needs no external data at build time.

Usage (from the repository root):
    python3 msgfmt/tools/gen_unicode_tables.py > msgfmt/src/unicode_tables.inc

Different Python versions bundle different Unicode versions; the version used
is recorded in the generated file.
"""

from __future__ import annotations

import sys
import unicodedata
from typing import Iterator

LETTER_OR_DIGIT = frozenset({"Lu", "Ll", "Lt", "Lm", "Lo", "Nd"})
MAX_CODE_POINT = 0x10FFFF
RANGES_PER_LINE = 4


def letter_or_digit_ranges() -> Iterator[tuple[int, int]]:
    """Yield inclusive (first, last) ranges of letter-or-digit code points."""
    start = None
    for cp in range(MAX_CODE_POINT + 1):
        inside = unicodedata.category(chr(cp)) in LETTER_OR_DIGIT
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            yield start, cp - 1
            start = None
    if start is not None:
        yield start, MAX_CODE_POINT


def main() -> None:
    ranges = list(letter_or_digit_ranges())
    out = sys.stdout
    out.write(
        "// Generated by msgfmt/tools/gen_unicode_tables.py from Unicode "
        f"{unicodedata.unidata_version}; do not edit.\n"
        "// Code points of general categories Lu, Ll, Lt, Lm, Lo and Nd as "
        "sorted, disjoint,\n"
        "// non-adjacent inclusive ranges.\n\n"
        f"constexpr std::array<CodePointRange, {len(ranges)}> "
        "kLetterOrDigitRanges = {{\n"
    )
    for i in range(0, len(ranges), RANGES_PER_LINE):
        chunk = ranges[i:i + RANGES_PER_LINE]
        cells = " ".join(f"{{0x{a:05X}, 0x{b:05X}}}," for a, b in chunk)
        out.write(f"    {cells}\n")
    out.write("}};\n")


if __name__ == "__main__":
    main()
